"""Apply the current palette as a native Chromium seed before browser startup."""

import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path

VARIANTS = {"tonal-spot": 1, "neutral": 2, "vibrant": 3, "expressive": 4}
THEME_SECTIONS = ("browser", "extensions", "autogenerated")


def write_json(path, value):
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, delete=False) as staged:
        temporary = Path(staged.name)
        try:
            json.dump(value, staged)
            staged.close()
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)


def update_theme(profile, action, seed, variant, config):
    lock = profile.parent / "SingletonLock"
    if lock.exists() or lock.is_symlink():
        if action == "launch":
            return
        raise ValueError(
            "Close the browser completely before applying or restoring a seed."
        )

    preferences = profile / "Preferences"
    backup = profile / "browser-theme-seed-test.json"
    prefs = json.loads(preferences.read_text())

    if action == "restore":
        saved = json.loads(backup.read_text())
        for section in THEME_SECTIONS:
            if saved[section] is None:
                prefs.get(section, {}).pop("theme", None)
            else:
                prefs.setdefault(section, {})["theme"] = saved[section]
        write_json(preferences, prefs)
        backup.unlink()
        print("Previous theme settings restored. Open the browser.")
        return

    if not seed.startswith("#"):
        palette = json.loads((config / "colors/current.json").read_text())
        seed = palette.get(seed)
    if not isinstance(seed, str) or not re.fullmatch(r"#[0-9a-fA-F]{6}", seed):
        raise ValueError("Seed must be a palette color or #RRGGBB.")

    if not backup.exists():
        write_json(
            backup,
            {
                section: prefs.get(section, {}).get("theme")
                for section in THEME_SECTIONS
            },
        )

    # Native picker state, not an extension or autogenerated policy theme.
    theme = prefs.setdefault("browser", {}).setdefault("theme", {})
    theme.update(
        user_color2=int(seed[1:], 16) - 0x1000000,
        color_variant2=VARIANTS[variant],
        is_grayscale2=False,
        follows_system_colors=False,
    )
    extension_theme = prefs.setdefault("extensions", {}).setdefault("theme", {})
    extension_theme.update(id="user_color_theme_id", system_theme=0)
    extension_theme.pop("pack", None)
    prefs.get("autogenerated", {}).get("theme", {}).pop("color", None)
    write_json(preferences, prefs)
    if action == "apply":
        print(f"Native seed {seed} ({variant}) applied. Open the browser.")


def user_data_directory(browser, config):
    if sys.platform == "darwin":
        product = "net.imput.helium" if browser == "helium" else "Google/Chrome"
        return Path.home() / "Library/Application Support" / product
    if os.environ.get("CHROME_USER_DATA_DIR"):
        return Path(os.environ["CHROME_USER_DATA_DIR"]).expanduser()
    config = Path(os.environ.get("CHROME_CONFIG_HOME", str(config)))
    return config / ("net.imput.helium" if browser == "helium" else "google-chrome")


def launch_profile(command, browser, config):
    if any(
        arg in ("--version", "--product-version", "--help", "-h") for arg in command[1:]
    ):
        return None
    flags = argparse.ArgumentParser(
        add_help=False, allow_abbrev=False, exit_on_error=False
    )
    flags.add_argument("--user-data-dir", type=Path)
    flags.add_argument("--profile-directory")
    flags.add_argument("--guest", action="store_true")
    flags.add_argument("--type")
    options, _ = flags.parse_known_args(command[1:])
    if options.guest or options.type:
        return None
    root = (options.user_data_dir or user_data_directory(browser, config)).expanduser()
    name = options.profile_directory
    if name is None:
        state = root / "Local State"
        name = (
            json.loads(state.read_text()).get("profile", {}).get("last_used", "Default")
            if state.exists()
            else "Default"
        )
    if not isinstance(name, str) or Path(name).name != name or name in (".", ".."):
        raise ValueError("Invalid browser profile directory.")
    return root / name


def main():
    config = Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config")))
    arguments = sys.argv[1:]
    command = []
    if "--" in arguments:
        separator = arguments.index("--")
        arguments, command = arguments[:separator], arguments[separator + 1 :]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("apply", "restore", "launch"))
    parser.add_argument("--browser", choices=("helium", "chrome"), default="helium")
    parser.add_argument("--profile", type=Path)
    parser.add_argument("--seed", default="bg", help="palette key or #RRGGBB")
    parser.add_argument("--variant", choices=VARIANTS, default="neutral")
    args = parser.parse_args(arguments)
    if args.action == "launch":
        if not command or args.profile:
            parser.error("launch requires -- BROWSER [ARGS], without --profile")
        try:
            profile = launch_profile(command, args.browser, config)
            if profile is not None and (profile / "Preferences").is_file():
                update_theme(profile, args.action, args.seed, args.variant, config)
        except FileNotFoundError:
            pass
        except (
            OSError,
            ValueError,
            TypeError,
            KeyError,
            AttributeError,
            argparse.ArgumentError,
        ) as error:
            print(f"browser-theme: theme skipped: {error}", file=sys.stderr)
        os.execvp(command[0], command)
    if command:
        parser.error("a browser command is only accepted with launch")
    profile = args.profile or user_data_directory(args.browser, config) / "Default"
    update_theme(
        profile.expanduser().resolve(), args.action, args.seed, args.variant, config
    )


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, TypeError, KeyError, AttributeError) as error:
        sys.exit(f"browser-theme: {error}")
